import json
segs=json.load(open('cut.words.json'))
C=["واحدة من أفضل استراتيجيات البزنس هي إنك تكوني أنانية متل الرجال",
"شغلة لاحظتها عند الرجال لما يكونوا عم يشتغلوا حتى يبنوا حياتهم المهنية",
"هي إنهم ما بيكون عندهم نفس الشعور بالذنب اللي عند البنات",
"لما يقرروا يحطوا نفسهم وأهدافهم أولوية",
"يعني الرجال ما بيخجلوا من إنهم يحطوا حالهم وأهدافهم أولوية",
"لأنه بالنسبة إلهم الناس التانيين بتجي بعدين عندهم بالقائمة",
"يعني إذا الرجال قرر يركز على شغله ويبني بزنس عادي جدا عنده يرفض طلعة مع رفقاته ويبعد عن الناس",
"أو حتى يختفي فترة ليحقق هدفه",
"والأهم إنه ما بيضل يسأل كل شخص عن رأيه باختياراته المهنية والبزنس اللي بلش فيه",
"بس البنت بتضل دايما تفكر طيب إذا زعلوا مني طيب إذا حسوا إني تغيرت طيب إذا قصرت بحق حدا",
"طب لا خليني أنا ضحي بحلمي مشان غيري",
"لأنه تعلمنا دايما نعطي الكل على حساب وقتنا حتى لما يكون عم يكلفنا كل شي",
"بس لما نجي نحكي على الحياة المهنية",
"وأوقات البنت بتكون عم تضحي بأهدافها كرمال ناس",
"لو كانوا بمحلها ما كانوا ضحوا بنفس الشي كرمالها",
"فإذا بدك تنجحي بحياتك",
"تعلمي هالشغلة من عند الرجال",
"لما يكون عندك هدف خلي إله أولوية",
"ومو كل حدا لما يطلب منك شي لازم تساعديه ومو كل فرصة لازم توافقي عليها",
"ومو لازم تبرري للكل ليش عم تختاري شغلك على حساب طلعة أو قعدة",
"أو حتى وقتك لحالك",
"وكل شي تاني بيجي بعدين"]
assert len(C)==len(segs),(len(C),len(segs))
caps=[]
for s,c in zip(segs,C):
    ws=c.split(); W=s['w']
    if len(ws)==len(W): caps+=[[x,a,b] for x,(a,b,_) in zip(ws,W)]
    else:
        a0,b0=W[0][0],W[-1][1]; L=sum(len(x) for x in ws); t=a0
        for x in ws: d=(b0-a0)*len(x)/L; caps.append([x,round(t,2),round(t+d,2)]); t+=d
DUR=3030/30
st=lambda i: round(segs[i]['w'][0][0]-0.1,2)
P=[(0,'hook'),(1,'s1'),(6,'s2'),(9,'s3'),(12,'s4'),(15,'s5')]
T={'s1':'الرجال ما بيحسوا بالذنب لما يحطوا حالهم أولوية','s2':'بيرفض، بيختفي… وما بيبرر لحدا',
   's3':'والبنت؟ «طيب إذا زعلوا مني؟»','s4':'بتضحي كرمال ناس ما كانوا ضحوا كرمالها','s5':'خلي هدفك أولوية… وكل شي تاني بيجي بعدين'}
sec=[]
for k,(i,n) in enumerate(P):
    a=0 if n=='hook' else st(i); b=st(P[k+1][0]) if k+1<len(P) else DUR
    sec.append([a,b,n,T.get(n,''),4 if n=='hook' else 2])
segst=[]
for s in segs:
    t=round(s['w'][0][0],2)
    if not segst or t-segst[-1]>=3.5: segst.append(t)
json.dump({'caps':caps,'sec':sec,'segst':segst,'dur':DUR},open('fx/timeline.json','w'),ensure_ascii=False)
for x in sec: print(x)
