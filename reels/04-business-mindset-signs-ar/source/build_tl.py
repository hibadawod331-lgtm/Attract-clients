assert len(C)==len(segs)
caps=[]
for s,c in zip(segs,C):
    ws=c.split(); W=s['w']
    if len(ws)==len(W): caps+= [[x,a,b] for x,(a,b,_) in zip(ws,W)]
    else:
        a0,b0=W[0][0],W[-1][1]; L=sum(len(x) for x in ws); t=a0
        for x in ws: d=(b0-a0)*len(x)/L; caps.append([x,round(t,2),round(t+d,2)]); t+=d
DUR=2671/30
st=lambda i: round(segs[i]['w'][0][0]-0.1,2)
P=[(0,'hook'),(2,'p1'),(4,'p2'),(9,'p3'),(13,'p4'),(19,'p5'),(28,'p6')]
T={'p1':'ما بتحبي حدا يقلك "لا"','p2':'بتحبي تعملي الأشياء بطريقتك','p3':'ما بتتقبلي الشي اللي ما عجبك… بتغيريه',
   'p4':'بتحلي المشاكل لحالك','p5':'حاسة إنك مو مخلوقة لحياة عادية','p6':'إلك رأيك الخاص… وما بتقتنعي بسهولة'}
sec=[]
for k,(i,n) in enumerate(P):
    a=0 if n=='hook' else st(i); b=st(P[k+1][0]) if k+1<len(P) else DUR
    num=n[1:] if n!='hook' else ''
    sec.append([a,b,n,f'<bdi dir="ltr">{num}.</bdi> {T[n]}' if num else '',4 if n=='hook' else 2])
segst=[]; 
for s in segs:
    t=round(s['w'][0][0],2)
    if not segst or t-segst[-1]>=3.5: segst.append(t)
json.dump({'caps':caps,'sec':sec,'segst':segst,'dur':DUR},open('fx/timeline.json','w'),ensure_ascii=False)
for x in sec: print(x)
